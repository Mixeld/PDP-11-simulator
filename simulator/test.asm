loop:
    MOV  @#177560, R0      ; читаем статус клавиатуры
    BIC  #177400, R0       ; обнуляем старший байт (оставляем только младший)
    BIT  #200, R0          ; проверяем бит 7 (= 200 восьмеричное)
    BEQ  loop              ; если 0 — нет символа, ждём
    
    MOV  @#177562, R0      ; читаем символ
    BIC  #177400, R0       ; оставляем только младший байт
    
    MOV  R0, @#177566      ; выводим символ
    
    BR   loop              ; повторяем